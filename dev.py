def cmd_run(args):
    playback = None
    if args.scenario:
        # Scenario errors fail here, before anything is built or launched.
        require_piloting_platform()
        if args.live:
            playback = LivePlayback(args.scenario)
        else:
            playback = MoviePlayback(
                args.scenario, keep_card=args.keep_card, no_card=args.no_card
            )
    dolphin = find_dolphin()
    if dolphin is None:
        raise DevError(
            "could not find Dolphin. Set \"dolphin\" in "
            f"{CONFIG_FILE.name} to its executable, e.g. "
            '{"dolphin": "C:/path/to/Dolphin.exe"}'
        )
    if playback:
        playback.check(dolphin)
    if (
        isinstance(playback, MoviePlayback)
        and not playback.no_card
        and not args.scenario.startswith(NEW_SAVE_PREFIX)
    ):
        ensure_training_save(dolphin, args)
    launch_training(args, dolphin, playback)


def launch_training(args, dolphin, playback=None, log_reps=True):
    """Build the training build, launch it in `dolphin` (with `playback`, if
    any, followed to its end)."""
    dol = build(
        "training",
        authoring=args.authoring,
        tech_pool=args.tech_pool,
    )
    stop_tracked_dolphin(load_state())
    from tools import reps, shot

    # Without authoring tools nothing is logged: no mark, so `reps` says so.
    save_state(rep_log_mark=reps.mark(reps.log_path(dolphin_user_dir())) if args.authoring else None)
    shot.clear_shots(SHOTS_DIR)
    extra = playback.prepare() if playback else []
    if args.authoring:
        extra += reps.launch_args()
    game_dol = assemble_game(dol)
    say(f"Launching {dolphin.name} ...")
    kw = {}
    if IS_WINDOWS:
        kw["creationflags"] = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kw["start_new_session"] = True
    proc = subprocess.Popen(
        [str(dolphin), "-e", str(game_dol), *extra],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        **kw,
    )
    save_state(dolphin_pid=proc.pid)
    if playback:
        say(f"Waiting for the game window (up to {WINDOW_TIMEOUT:g}s) ...")
        playback.follow()
        if args.authoring and log_reps:
            print_rep_log(load_state().get("rep_log_mark", 0))


MOVIE_OPTION = b"--movie"  # in the usage text of a Dolphin that can play movies


def file_contains(path, needle, chunk=1 << 20):
    """Whether the bytes `needle` occur in the file at `path`, read in chunks
    (a Dolphin executable is tens of MB)."""
    tail = b""
    with open(path, "rb") as f:
        while block := f.read(chunk):
            if needle in tail + block:
                return True
            tail = block[-(len(needle) - 1) :]
    return False


def check_movie_playback(dolphin):
    """Fail unless `dolphin` will play a scenario movie: its executable must
    offer the `--movie` option, and RetroAchievements hardcore mode (in which
    Dolphin silently refuses movies) must be off. Never falls back to
    keyboard playback."""
    live = "or use `run --scenario <name> --live` for keyboard playback."
    if not file_contains(dolphin, MOVIE_OPTION):
        raise DevError(
            f"{dolphin} has no movie playback option (-m/--movie), so it "
            "cannot play the scenario as a movie. Point \"dolphin\" in "
            f"{CONFIG_FILE.name} at a recent Dolphin, {live}"
        )
    from tools import pad

    ini = dolphin_user_dir() / "Config" / "RetroAchievements.ini"
    ra = (pad.read_section(ini, "Achievements") if ini.is_file() else None) or {}
    if all(ra.get(k, "").lower() == "true" for k in ("Enabled", "HardcoreEnabled")):
        raise DevError(
            "Dolphin refuses to play movies while RetroAchievements hardcore "
            f"mode is on ({ini}). Turn hardcore mode off in Dolphin, {live}"
        )


