def verify_vanilla_disc(disc):
    """Fail unless `dtk disc verify` fully matches `disc` to REDUMP_NAME.
    dtk exits 0 even on a mismatch, so its report is read instead."""
    ensure_dtk()
    say(f"Verifying {disc} ...")
    r = run([DTK, "disc", "verify", disc], capture_output=True)
    out = (r.stdout + r.stderr).decode("utf-8", errors="replace")
    redump = re.search(r"(?m)^Redump: (.*)$", out)
    verified = (
        r.returncode == 0
        and redump is not None
        and redump.group(1).strip() == f"{REDUMP_NAME} ✅"
        and "❌" not in out
    )
    if not verified:
        marks = {"✅": "(ok)", "❌": "(MISMATCH)", "❓": "(?)"}
        report = "\n".join(
            "  " + re.sub("[✅❌❓]", lambda m: marks[m.group()], line)
            for line in out.splitlines()
            if re.match(r"(Redump|CRC32|SHA-1|MD5) ?:", line)
        )
        with open(disc, "rb") as f:
            f.seek(0x200)
            nkit = f.read(4) == b"NKIT"
        raise DevError(
            f"{disc} failed verification: it is not a clean dump of {REDUMP_NAME} "
            "(Melee NTSC-U 1.02), so a patch made from it might not apply to "
            "players' copies.\n"
            + (report or out.strip())
            + (
                "\nIt is an NKit image (trimmed): restore it to a full ISO with NKit first."
                if nkit
                else ""
            )
        )
    say("Disc verified against Redump.")


