def stage_iso_root(game):
    """Lay the assembled game folder out as gc_fst's `rebuild` reads it:
    `&&systemdata/` with ISO.hdr (boot.bin + bi2.bin), AppLoader.ldr and
    Start.dol, and the disc's filesystem (our `files/`) at the top level."""
    remove_tree(ISO_ROOT)
    system = ISO_ROOT / "&&systemdata"
    system.mkdir(parents=True)
    sys_dir = game / "sys"
    (system / "ISO.hdr").write_bytes(
        (sys_dir / "boot.bin").read_bytes() + (sys_dir / "bi2.bin").read_bytes()
    )
    link_or_copy(sys_dir / "apploader.img", system / "AppLoader.ldr")
    link_or_copy(sys_dir / "main.dol", system / "Start.dol")
    for src in sorted(p for p in (game / "files").rglob("*") if p.is_file()):
        dest = ISO_ROOT / src.relative_to(game / "files")
        dest.parent.mkdir(parents=True, exist_ok=True)
        link_or_copy(src, dest)


