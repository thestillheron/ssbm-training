def play_movie(items, movie_path):
    """Follow a scenario movie that Dolphin is playing from power-on: wait
    for the game window, take each shot at its frame on the wall clock, and
    return once the movie has ended (the keyboard-bound controller then has
    port 1)."""
    from tools import pad, scenario_live, shot, win_pilot

    user = dolphin_user_dir()
    pid = load_state().get("dolphin_pid")

    def check_no_dialog():
        # Dolphin reports a movie it rejects (bad file, wrong game) with a
        # modal dialog such as "Warning"; its own windows are titled "Dolphin...".
        for _hwnd, title, owner in win_pilot.visible_windows():
            if owner == pid and not title.startswith("Dolphin"):
                raise DevError(
                    f"Dolphin opened a '{title}' dialog while starting the movie "
                    f"{movie_path}: it probably rejected it (the "
                    "dialog says why). Close Dolphin, or use `run --scenario "
                    "<name> --live` for keyboard playback."
                )

    def find():
        check_no_dialog()
        return find_game_window()

    try:
        key = shot.screenshot_key(user)
        hwnd = scenario_live.wait_for_window(find, WINDOW_TIMEOUT)
        backend = win_pilot.Win32Backend()

        def take(label):
            return shot.take_shot(
                label, key, hwnd, backend, shot.screenshots_dir(user), SHOTS_DIR
            )

        frames = scenario_live.follow_movie(items, take, say=say, check=check_no_dialog)
    except pad.PadError as e:
        raise DevError(str(e))
    say(f"Movie finished ({frames} frames); the keyboard-bound controller has port 1.")


