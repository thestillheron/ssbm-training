# Dolphin.ini [Core] SlotA values (Dolphin's EXIDeviceType).
SLOT_RAW_CARD = "1"
SLOT_KINDS = {"1": "a raw memory card file", "8": "a GCI folder", "255": "nothing"}
SLOT_A_DEFAULT = "8"  # Dolphin's default when Dolphin.ini doesn't set SlotA
CARD_REGIONS = (".USA", ".EUR", ".JAP")


def slot_a_card():
    """The raw memory card file Dolphin uses in slot A for GALE01, from
    Dolphin.ini; DevError if slot A isn't an existing raw card file."""
    from tools import pad

    ini = dolphin_user_dir() / "Config" / "Dolphin.ini"
    fix = (
        "Movie runs need a raw memory card file in slot A to snapshot: in "
        "Dolphin, Config > GameCube > Slot A: Memory Card (holding the save "
        "with everything unlocked)."
    )
    if not ini.is_file():
        raise DevError(f"cannot find the slot A memory card: no {ini}. {fix}")
    core = pad.read_section(ini, "Core") or {}
    slot = core.get("SlotA", SLOT_A_DEFAULT)
    if slot != SLOT_RAW_CARD:
        kind = SLOT_KINDS.get(slot, f"device type {slot}")
        raise DevError(f"Dolphin's slot A holds {kind}, not a raw memory card file ({ini}). {fix}")
    configured = core.get("MemcardAPath")
    if configured:
        # Like Dolphin: the file name's region code (or none) becomes the
        # game's region, here USA.
        path = Path(configured)
        stem = path.stem
        for region in CARD_REGIONS:
            if stem.endswith(region):
                stem = stem[: -len(region)]
        card = path.with_name(f"{stem}.USA{path.suffix}")
    else:
        card = dolphin_user_dir() / "GC" / "MemoryCardA.USA.raw"
    if not card.is_file():
        raise DevError(f"Dolphin's slot A memory card {card} does not exist ({ini}). {fix}")
    return card


def snapshot_card():
    """Copy the slot-A card to CARD_SNAPSHOT (replacing any earlier one)."""
    card = slot_a_card()
    CARD_SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(card, CARD_SNAPSHOT)
    say(
        f"Memory card snapshot for movie runs: {CARD_SNAPSHOT} (copied from "
        f"{card}). Refresh it after unlocking things: python dev.py snapshot-card"
    )


def ensure_card_snapshot():
    """Snapshot the slot-A card for movie runs if there is no snapshot yet."""
    if not CARD_SNAPSHOT.is_file():
        snapshot_card()


def snapshot_lacks_training_save():
    """Whether the snapshot is a memory card with no save for the training
    build. A file that is not a memory card (unknown) is left alone."""
    from tools.memcard import TRAINING_GAME_ID, NotAMemoryCard, card_game_ids

    try:
        return TRAINING_GAME_ID not in card_game_ids(CARD_SNAPSHOT)
    except NotAMemoryCard:
        return False


